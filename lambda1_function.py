#lambda expression for defining square of a number

square = lambda x:x**2
print(square(5))

#lambda expression for define cube of a number

cube=lambda y:y**3
print(cube(2))

#lambda expression for define squareroot of a number
squrt=lambda x:x**0.5
print(squrt(12))

#length of string
length=lambda x:len(x)
print(length('hi'))

#name atribute from dictionary
n=lambda y:y['name']
print(n({'age':23,'name':'Ajith'}))

#sum of two numbers
sum=lambda a,b:a+b
print(sum(1,4))

#product of four numbers
p=lambda a,b,c,d:a*b*c*d
print(p(4,5,7,8))

#find the last element in a list
l=lambda a:a[-1]
print(l([1,2,3,4,5]))

#find the first elemnent in a list

i=lambda c:c[0]
print(i([6,5,4,8]))























































